static const char *const *glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    for (size_t i = 0; i < sizeof k_glyphs / sizeof *k_glyphs; i++)
        if (k_glyphs[i].c == c) return k_glyphs[i].rows;
    return NULL;   /* space and anything unknown: blank */
}

int ui_text_width(const char *s, int scale) { return (int)strlen(s) * 6 * scale; }

static void dot(ui_image_t *im, int x, int y, int scale, uint32_t rgba) {
    for (int j = 0; j < scale; j++)
        for (int i = 0; i < scale; i++) {
            int px = x + i, py = y + j;
            if (px >= 0 && py >= 0 && px < im->w && py < im->h) im->px[py * im->w + px] = rgba;
        }
}

/* Text at x, y (top left), each glyph pixel scale x scale, with a dark shadow one pixel down right. */
void ui_text(ui_image_t *im, int x, int y, int scale, const char *s, uint32_t rgba) {
    for (int pass = 0; pass < 2; pass++)
        for (int k = 0; s[k]; k++) {
            const char *const *g = glyph(s[k]);
            for (int r = 0; g && r < 7; r++)
                for (int c = 0; c < 5; c++)
                    if (g[r][c] == '#')
                        dot(im, x + (k * 6 + c) * scale + (pass ? 0 : scale / 2 + 1),
                            y + r * scale + (pass ? 0 : scale / 2 + 1), scale, pass ? rgba : UI_SHADOW);
        }
}

void ui_rect(ui_image_t *im, int x, int y, int w, int h, uint32_t rgba) {
    for (int j = y < 0 ? 0 : y; j < y + h && j < im->h; j++)
        for (int i = x < 0 ? 0 : x; i < x + w && i < im->w; i++) im->px[j * im->w + i] = rgba;
}
