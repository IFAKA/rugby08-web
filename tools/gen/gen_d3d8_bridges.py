#!/usr/bin/env python3
"""Generate the guest D3D8 vtables from d3d8to9's interface declarations (vtable order).

Output (gitignored): gen/runtime/d3d8_vtables.c. For every interface, one entry per vtable slot
(IUnknown and resource bases included): name, stdcall pop bytes, handler. The handler is
d3d8_<Iface>_<Method> if runtime/d3d8 defines it (an `HLE_D3D(Iface, Method)` definition), else
the declaring base's d3d8_<Base>_<Method>, else a generated stub that logs "D3D8 UNIMPL <Iface>::<Method>" once and returns E_NOTIMPL (0 for
methods that do not return HRESULT). Handler ABI = rt_hle_fn (a[0] = guest `this`).
Prints one line.
"""

import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent.parent
SRC = root / "third_party/d3d8to9/source/d3d8.hpp"
OUT = root / "gen/runtime/d3d8_vtables.c"

IUNKNOWN = [("HRESULT", "QueryInterface", 2), ("ULONG", "AddRef", 0), ("ULONG", "Release", 0)]


def parse():
    text = SRC.read_text()
    ifaces: dict = {"IUnknown": (None, IUNKNOWN)}
    order = []
    for m in re.finditer(r"interface\s+(\w+)\s*:\s*public\s+(\w+)\s*\{(.*?)\};", text, re.S):
        name, base, body = m.groups()
        meths = []
        for mm in re.finditer(r"virtual\s+([\w\s\*]+?)\s+STDMETHODCALLTYPE\s+(\w+)\((.*?)\)\s*=\s*0;", body, re.S):
            ret, meth, params = mm.group(1).strip(), mm.group(2), mm.group(3).strip()
            n = 0 if params in ("", "void") else params.count(",") + 1
            meths.append((ret, meth, n))
        ifaces[name] = (base, meths)
        order.append(name)
    return ifaces, order


def slots(ifaces, name):
    """[(declaring iface, ret, method, nparams)] in vtable order."""
    base, meths = ifaces[name]
    return (slots(ifaces, base) if base else []) + [(name, r, m, n) for r, m, n in meths]


def defined():
    """Handlers runtime/d3d8 implements: HLE_D3D(Iface, Method) { definitions."""
    out = set()
    for src in (root / "runtime/d3d8").glob("*.cpp"):
        out |= {f"d3d8_{i}_{m}" for i, m in re.findall(r"\bHLE_D3D\((\w+),\s*(\w+)\)\s*\{", src.read_text())}
    return out


def main():
    ifaces, order = parse()
    have = defined()
    decls, stubs, tables = set(), [], []
    for name in order:
        rows = []
        for decl, ret, meth, n in slots(ifaces, name):
            own, inh = f"d3d8_{name}_{meth}", f"d3d8_{decl}_{meth}"
            own = own if own in have else "0"
            inh = inh if inh in have else "0"
            decls.update({x for x in (own, inh) if x != "0"})
            stub = f"stub_{name}_{meth}"
            hr = "1" if ret == "HRESULT" else "0"
            stubs.append(
                f'static uint32_t {stub}(const uint32_t *a) {{ (void)a; return d3d8_unimpl("{name}::{meth}", {hr}); }}'
            )
            rows.append(f'    {{ "{name}::{meth}", {4 * (n + 1)}, {own}, {inh}, {stub} }},')
        tables.append(
            f"const d3d8_slot_t d3d8_vt_{name}[] = {{\n" + "\n".join(rows) + "\n};\n"
            f"const int d3d8_vt_{name}_n = {len(rows)};\n"
        )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "/* generated by tools/gen/gen_d3d8_bridges.py from third_party/d3d8to9/source/d3d8.hpp -- do not edit */\n"
        '#include "d3d8_bridge.h"\n\n'
        + "".join(f"uint32_t {d}(const uint32_t *a);\n" for d in sorted(decls))
        + "\n"
        + "\n".join(stubs)
        + "\n\n"
        + "\n".join(tables)
    )
    total = sum(len(slots(ifaces, n)) for n in order)
    bound = sum(
        1 for n in order for d, r, m, k in slots(ifaces, n) if f"d3d8_{n}_{m}" in have or f"d3d8_{d}_{m}" in have
    )
    print(f"gen_d3d8_bridges: {len(order)} interfaces, {bound}/{total} slots implemented -> {OUT.relative_to(root)}")


if __name__ == "__main__":
    main()
