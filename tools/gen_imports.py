#!/usr/bin/env python3
"""Generate the import-bridge table from the exe's IAT + Wine .spec signatures.

Outputs (gitignored, derived from the exe):
  gen/runtime/imports.c      226 bridges: IAT slot VA, name, stdcall pop bytes, weak hle_<Name>
  analysis/imports_sig.json  the resolved signatures (for humans and other generators)
Prints one line. Fails if any import has no signature (never guess a pop count).

Handler ABI (runtime/include/rt.h): uint32_t hle_<Name>(const uint32_t *a)
  a[k] is the k-th 32-bit argument slot on the guest stack; return value -> eax.
"""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
specs = root / "third_party/wine-specs"
SLOTS = {"int64": 2, "double": 2, "int128": 4, "float": 1}

def parse_spec(path):
    by_name, by_ord = {}, {}
    for line in path.read_text().splitlines():
        m = re.match(r"\s*(@|\d+)\s+(stdcall|cdecl|varargs|thiscall)\s+((?:-\S+\s+)*)(\S+)\((.*?)\)", line)
        if not m:
            continue
        ordv, conv, flags, name, args = m.groups()
        if "-arch=win64" in flags or "-arch=!i386" in flags:
            continue
        argv = args.split()
        slots = sum(SLOTS.get(t, 1) for t in argv)
        rec = {"conv": conv, "args": argv, "slots": slots, "name": name}
        by_name.setdefault(name, rec)
        if ordv != "@":
            by_ord[int(ordv)] = rec
    return by_name, by_ord

tables = {}
for p in specs.glob("*.spec"):
    tables[p.stem.upper() + ".DLL"] = parse_spec(p)
kb_name, _ = tables.get("KERNELBASE.DLL", ({}, {}))

pe = json.load(open(root / "analysis/pe_analysis.json"))
base = pe["image_base"]
out, missing = [], []
for imp in pe["imports"]:
    dll = imp["dll"].upper()
    by_name, by_ord = tables.get(dll, ({}, {}))
    if imp["name"]:
        rec = by_name.get(imp["name"]) or (kb_name.get(imp["name"]) if dll == "KERNEL32.DLL" else None)
    else:
        rec = by_ord.get(imp["ordinal"])
    if rec is None:
        missing.append(f"{dll}!{imp['name'] or imp['ordinal']}")
        continue
    out.append({"dll": dll, "name": rec["name"], "iat_va": base + imp["iat_rva"],
                "conv": rec["conv"], "slots": rec["slots"], "args": rec["args"],
                "pop": 4 * rec["slots"] if rec["conv"] == "stdcall" else 0})
if missing:
    print(f"gen_imports: FAIL no signature for {len(missing)}: {' '.join(missing[:20])}")
    sys.exit(1)

out.sort(key=lambda r: r["iat_va"])
json.dump(out, open(root / "analysis/imports_sig.json", "w"), indent=1)

# Which handlers exist: `HLE(Name) {` definitions anywhere in runtime/ or platform/ (no weak
# symbols: Mach-O and wasm treat undefined weak references differently).
import re as _re
impl = set()
for src in list((root / "runtime").rglob("*.c")) + list((root / "runtime").rglob("*.cpp")) + \
           list((root / "platform").rglob("*.c")) + list((root / "platform").rglob("*.cpp")):
    impl |= set(_re.findall(r"\bHLE\((\w+)\)\s*\{", src.read_text(errors="replace")))

gdir = root / "gen/runtime"
gdir.mkdir(parents=True, exist_ok=True)
L = ["/* GENERATED by tools/gen_imports.py -- do not edit */", '#include "rt.h"', ""]
for r in out:
    if r["name"] in impl:
        L.append(f"uint32_t hle_{r['name']}(const uint32_t *a);")
L += ["", "const rt_import_t rt_imports[] = {"]
for r in out:
    fn = f"hle_{r['name']}" if r["name"] in impl else "0"
    L.append(f"  {{0x{r['iat_va']:08X}u, \"{r['dll']}\", \"{r['name']}\", {r['pop']}, {r['slots']}, {fn}}},")
L += ["};", f"const uint32_t rt_import_count = {len(out)};", ""]
(gdir / "imports.c").write_text("\n".join(L))
conv = {}
for r in out:
    conv[r["conv"]] = conv.get(r["conv"], 0) + 1
print(f"gen_imports: {len(out)} imports resolved {conv}, {sum(r['name'] in impl for r in out)} implemented -> gen/runtime/imports.c")
